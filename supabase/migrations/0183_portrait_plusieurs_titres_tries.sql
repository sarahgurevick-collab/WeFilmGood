-- Puis, comme en 0181 : les « titre - auteur » dont le titre seul existe
-- maintenant (« romeo et juliette - shakespeare » → « romeo et juliette »).
insert into public.personality_libre_alias (question_key, alias, texte)
with r as (
  select k.key, substr(k.value, 7) as t, count(*) as n
  from public.profiles p, jsonb_each_text(p.personality_answers) k
  where k.value like 'autre:%' group by 1, 2
),
long as (select key, t, n, trim(split_part(t, ' - ', 1)) as base from r where t like '% - %')
select l.key, public.normaliser_reponse_portrait(l.t), b.t
from long l join r b on b.key = l.key and b.t = l.base
where l.n >= 2 and l.base <> ''
on conflict (question_key, alias) do nothing;

