-- Les trois nuages, d'un bloc (plus de 1 000 mots : au-delà de ce que
-- l'API rend en une lecture).
create or replace function public.nuages_mots_cles_fiche()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(jsonb_object_agg(ligne, mots), '{}'::jsonb)
  from (select ligne, jsonb_agg(jsonb_build_array(label, poids) order by position) as mots
        from public.nuages_mots_cles group by ligne) x
  where auth.uid() is not null;
$$;
revoke all on function public.nuages_mots_cles_fiche() from public, anon;
grant execute on function public.nuages_mots_cles_fiche() to authenticated, service_role;

-- Un mot qu'on peut proposer : dans un nuage, ou posé par l'IA sur une fiche.
create or replace function public.mot_cle_proposable(p_keyword bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.keywords k join public.nuages_mots_cles n on n.slug = k.slug where k.id = p_keyword)
      or exists (select 1 from public.project_keywords pk
                  where pk.keyword_id = p_keyword and pk.source in ('ia', 'forme', 'sous_genre'));
$$;

-- Les suggestions pendant la frappe : d'abord les mots qui commencent par
-- ce qui est tapé, puis ceux qui le contiennent, puis les fautes de frappe
-- proches ; à égalité, les plus utilisés.
create or replace function public.suggerer_mots_cles(q text, p_limite int default 8)
returns table (label text)
language sql
stable
security definer
set search_path = public, extensions
as $$
  with t as (select lower(public.sans_accent(btrim(q))) as mot),
  candidats as (
    select k.id, coalesce(n.label, k.label_fr) as label, lower(public.sans_accent(k.label_fr)) as base, n.poids
    from public.keywords k
    left join public.nuages_mots_cles n on n.slug = k.slug, t
    where length(t.mot) >= 2
      and (lower(public.sans_accent(k.label_fr)) like '%' || replace(replace(t.mot, '%', ''), '_', '') || '%'
           or similarity(public.sans_accent(k.label_fr), t.mot) >= 0.45)
  )
  select c.label
  from candidats c, t
  where auth.uid() is not null and public.mot_cle_proposable(c.id)
  order by (c.base like t.mot || '%') desc,
           (c.base like '%' || t.mot || '%') desc,
           coalesce(c.poids, 0) + (select count(*) from public.project_keywords pk where pk.keyword_id = c.id) desc,
           c.label
  limit greatest(1, least(p_limite, 20));
$$;
revoke all on function public.suggerer_mots_cles(text, int) from public, anon;
grant execute on function public.suggerer_mots_cles(text, int) to authenticated, service_role;

-- L'enregistrement : seulement des mots existants et proposables. Un mot
-- déjà sur la fiche par la demande de l'auteur (WFG 1) peut rester.
create or replace function public.poser_mots_cles_auteur(p_project uuid, p_mots text[])
returns text[]
language plpgsql
security definer
set search_path = public, extensions
as $fn$
declare
  v_ids bigint[];
begin
  if not (public.is_admin() or exists (select 1 from public.projects where id = p_project and owner_id = auth.uid())) then
    raise exception 'Réservé à l''auteur de la fiche';
  end if;

  select coalesce(array_agg(id order by rang), '{}') into v_ids
  from (
    select distinct on (k.id) k.id, o.n as rang
    from unnest(coalesce(p_mots, '{}')) with ordinality o(m, n)
    join public.keywords k
      on k.slug = btrim(regexp_replace(lower(public.sans_accent(btrim(o.m))), '[^a-z0-9]+', '_', 'g'), '_')
    where public.mot_cle_proposable(k.id)
       or exists (select 1 from public.project_keywords pk
                   where pk.project_id = p_project and pk.keyword_id = k.id and pk.source = 'demande_auteur')
    order by k.id, o.n
  ) x
  where rang is not null;
  v_ids := v_ids[1:40];

  delete from public.project_keywords
   where project_id = p_project and source = 'demande_auteur' and not (keyword_id = any (v_ids));

  insert into public.project_keywords (project_id, keyword_id, source)
  select p_project, unnest(v_ids), 'demande_auteur'
  on conflict (project_id, keyword_id) do update set source = 'demande_auteur';

  return array(select k.label_fr from unnest(v_ids) with ordinality u(id, n) join public.keywords k on k.id = u.id order by u.n);
end;
